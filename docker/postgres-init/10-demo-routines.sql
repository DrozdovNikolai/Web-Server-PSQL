CREATE OR REPLACE FUNCTION public.calculate_order_total(
    order_id integer,
    tax_rate numeric DEFAULT 0.20)
RETURNS numeric
LANGUAGE sql
STABLE
AS $$
    SELECT round(subtotal * (1 + tax_rate), 2)
    FROM public.demo_orders
    WHERE id = order_id
$$;

CREATE OR REPLACE FUNCTION public.list_demo_orders(
    minimum_subtotal numeric DEFAULT 0)
RETURNS TABLE(order_id integer, customer_name text, subtotal numeric)
LANGUAGE sql
STABLE
AS $$
    SELECT id, demo_orders.customer_name, demo_orders.subtotal
    FROM public.demo_orders
    WHERE demo_orders.subtotal >= minimum_subtotal
    ORDER BY id
$$;

CREATE OR REPLACE FUNCTION public.format_value(value integer)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$ SELECT 'integer:' || value::text $$;

CREATE OR REPLACE FUNCTION public.format_value(value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$ SELECT 'text:' || value $$;

CREATE OR REPLACE FUNCTION public.open_demo_orders_report(
    minimum_subtotal numeric DEFAULT 0)
RETURNS refcursor
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    report_cursor refcursor := 'demo_orders_report';
BEGIN
    OPEN report_cursor FOR
        SELECT id AS order_id, customer_name, subtotal
        FROM public.demo_orders
        WHERE demo_orders.subtotal >= minimum_subtotal
        ORDER BY id;
    RETURN report_cursor;
END;
$$;

CREATE OR REPLACE PROCEDURE public.record_demo_event(message text)
LANGUAGE sql
AS $$
    INSERT INTO public.demo_events(message) VALUES (message)
$$;

COMMENT ON FUNCTION public.calculate_order_total(integer, numeric)
